"""HYDRA's single-cycle waves (firmware/src/eng_hydra.c).

Our own set in the spirit of a wave-scanning synth's ROM: seven families of eight (basic, harmonic, vowel, bell,
digital, spectral, texture). Each wave is one cycle of 256 int16 points, band-limited to HY_HARM harmonics so the
engine's linear read stays clean up to the middle of the keyboard, DC-free and normalised to one peak.

A wave is a spectrum (harmonic k: amplitude, sine phase) or a shape in time (x in [0, 1)), the latter measured by a
DFT over an oversampled cycle and resynthesised with its first HY_HARM harmonics.

Generated by tools/generate_assets.py into build/gen/melodee_hy.h as `const int16_t HY_WAVES[HY_NWAVE][256]` (flash; the engine
copies the waves a part uses into its RAM state).
"""
import math
import random
import re

N = 256                      # points per cycle
H = 64                       # harmonics kept (N / 4: the linear read's images stay low)
OS = 2048                    # oversampled cycle for shapes in time


def spectrum(parts):
    """parts: {k: amplitude} or {k: (amplitude, phase)} -> N samples"""
    out = [0.0] * N
    for k, a in parts.items():
        if k < 1 or k > H:
            continue
        amp, ph = a if isinstance(a, tuple) else (a, 0.0)
        if not amp:
            continue
        for i in range(N):
            out[i] += amp * math.sin(2 * math.pi * k * i / N + ph)
    return out


def shape(f):
    """f(x), x in [0, 1): one cycle in time -> its first H harmonics"""
    xs = [f(i / OS) for i in range(OS)]
    parts = {}
    for k in range(1, H + 1):
        re = sum(x * math.cos(2 * math.pi * k * i / OS) for i, x in enumerate(xs)) * 2 / OS
        im = sum(x * math.sin(2 * math.pi * k * i / OS) for i, x in enumerate(xs)) * 2 / OS
        a = math.hypot(re, im)
        if a > 1e-6:
            parts[k] = (a, math.atan2(re, im))
    return spectrum(parts)


def schroeder(k):
    """one phase rule for the buzz-like waves: a low crest factor (in sine phase the partials pile into one spike),
    the same in every wave of a family so a scan between them never cancels"""
    return math.pi * k * k / H


def formants(peaks, tilt=1.0, f0=130.0, bw=1.0):
    """a buzz through resonances: peaks [(Hz, gain, width Hz)], harmonic k at k * f0"""
    parts = {}
    for k in range(1, H + 1):
        f = k * f0
        g = 0.02
        for fc, gain, w in peaks:
            g += gain * math.exp(-0.5 * ((f - fc) / (w * bw)) ** 2)
        parts[k] = (g / k ** tilt, schroeder(k))
    return spectrum(parts)


def series(fn, ks=range(1, H + 1), phase=None):
    return spectrum({k: (fn(k), phase(k) if phase else 0.0) for k in ks})


def seeded(seed, fn):
    r = random.Random(seed)
    return spectrum({k: (fn(k, r), r.uniform(0, 2 * math.pi)) for k in range(1, H + 1)})


def saw(x):
    return 1.0 - 2.0 * x


def sync(r):
    return lambda x: 1.0 - 2.0 * ((x * r) % 1.0)


def pm(m, i):
    return lambda x: math.sin(2 * math.pi * x + i * math.sin(2 * math.pi * m * x))


def finish(w):
    dc = sum(w) / N
    w = [v - dc for v in w]
    m = max(1e-9, max(abs(v) for v in w))
    return [int(round(v * 30000 / m)) for v in w]


VOWELS = {                     # F1, F2, F3 (Hz)
    "VOX A": (730, 1090, 2440), "VOX E": (530, 1840, 2480), "VOX I": (270, 2290, 3010),
    "VOX O": (570, 840, 2410), "VOX U": (300, 870, 2240), "VOX AE": (660, 1720, 2410),
}


def vowel(name, tilt=1.0):
    f1, f2, f3 = VOWELS[name]
    return formants([(f1, 1.0, 90), (f2, 0.6, 110), (f3, 0.35, 160)], tilt)


WAVES = [
    # basic
    ("SINE", spectrum({1: 1.0})),
    ("TRI", series(lambda k: (-1) ** ((k - 1) // 2) / k ** 2 if k % 2 else 0)),
    ("SAW", series(lambda k: 1.0 / k)),
    ("SQR", series(lambda k: 1.0 / k if k % 2 else 0)),
    ("PULSE25", shape(lambda x: 1.0 if x < 0.25 else -1.0)),
    ("PULSE10", shape(lambda x: 1.0 if x < 0.10 else -1.0)),
    ("SOFTSW", series(lambda k: 1.0 / k ** 1.6)),
    ("HALFSIN", shape(lambda x: max(0.0, math.sin(2 * math.pi * x)))),
    # harmonic
    ("OCTAVE", spectrum({1: 1.0, 2: 0.8, 4: 0.45, 8: 0.2})),
    ("FIFTHS", spectrum({1: 1.0, 3: 0.75, 6: 0.5, 12: 0.3, 24: 0.15})),
    ("ODD 5", spectrum({1: 0.9, 3: 0.7, 5: 0.6, 7: 0.5, 9: 0.45})),
    ("EVEN", spectrum({1: 1.0, 2: 0.7, 4: 0.55, 6: 0.45, 8: 0.4, 10: 0.3, 12: 0.25})),
    ("DRAWBR", spectrum({1: 1.0, 2: 1.0, 3: 0.8, 4: 0.6, 6: 0.5, 8: 0.4})),
    ("ORGAN 2", spectrum({1: 1.0, 3: 0.7, 5: 0.5, 8: 0.35, 16: 0.2})),
    ("BRIGHT", series(lambda k: 1.0 / k ** 0.5)),
    ("HOLLOW", series(lambda k: (0.35 if k == 1 else 1.0 / k) if k % 2 else 0)),
    # vowel
    ("VOX A", vowel("VOX A")), ("VOX E", vowel("VOX E")), ("VOX I", vowel("VOX I")),
    ("VOX O", vowel("VOX O")), ("VOX U", vowel("VOX U")), ("VOX AE", vowel("VOX AE")),
    ("CHOIR", formants([(650, 1.0, 180), (1080, 0.7, 200), (2650, 0.3, 300)], 1.3)),
    ("NASAL", formants([(250, 1.0, 60), (2000, 0.8, 120), (3200, 0.4, 200)], 0.8)),
    # bell
    ("BELL", spectrum({1: 0.6, 3: 0.4, 5: 0.6, 7: 0.3, 11: 0.45, 13: 0.3, 17: 0.25, 23: 0.2})),
    ("CHIME", spectrum({1: 1.0, 4: 0.6, 9: 0.45, 16: 0.3, 25: 0.2, 36: 0.12})),
    ("GLASS", spectrum({1: 0.7, 5: 0.5, 9: 0.45, 13: 0.4, 17: 0.3, 21: 0.25})),
    ("TINE", spectrum({1: 1.0, 2: 0.15, 7: 0.4, 8: 0.3, 15: 0.1})),
    ("MALLET", spectrum({1: 1.0, 4: 0.5, 10: 0.3, 19: 0.12})),
    ("STEEL", spectrum({1: 0.8, 2: 0.5, 5: 0.5, 6: 0.4, 9: 0.35, 10: 0.3, 13: 0.2, 14: 0.15})),
    ("GONG", spectrum({1: 0.6, **{k: 0.25 + 0.05 * (k % 3) for k in range(9, 16)}})),
    ("KALIMBA", spectrum({1: 1.0, 5: 0.35, 6: 0.3, 14: 0.08})),
    # digital
    ("SYNC 2", shape(sync(1.5))), ("SYNC 3", shape(sync(2.6))), ("SYNC 5", shape(sync(4.3))),
    ("PM 1", shape(pm(2, 1.5))), ("PM 2", shape(pm(3, 2.5))), ("PM 3", shape(pm(1, 4.0))),
    ("BITS", shape(lambda x: round(math.sin(2 * math.pi * x) * 3.5) / 3.5)),
    ("STEPS", shape(lambda x: round(saw(x) * 3) / 3)),
    # spectral
    ("COMB", series(lambda k: 0 if k % 4 == 0 else 1.0 / k)),
    ("NOTCH", series(lambda k: 0 if 6 <= k <= 14 else 1.0 / k)),
    ("RAMP UP", series(lambda k: (k / H) * math.exp(-((k - 40) / 18) ** 2), phase=schroeder)),
    ("THIN", series(lambda k: 1.0 / k if 8 <= k <= 24 else (0.3 if k == 1 else 0))),
    ("BUZZ", series(lambda k: 0.5, phase=schroeder)),
    ("FORMNT", formants([(1560, 1.0, 200)], 0.9)),
    ("TWIN PK", formants([(650, 1.0, 120), (2210, 0.9, 140)], 0.6)),
    ("AIR", seeded(7, lambda k, r: r.uniform(0.2, 1.0) / k ** 0.3 if k >= 20 else (0.6 if k == 1 else 0))),
    # texture
    ("GRIT", seeded(11, lambda k, r: r.uniform(0.3, 1.0) / k ** 0.8)),
    ("DUST", seeded(23, lambda k, r: (r.uniform(0.4, 1.0) / k ** 0.6) if r.random() < 0.25 or k == 1 else 0)),
    ("FUZZ", shape(lambda x: math.tanh(4.0 * math.sin(2 * math.pi * x)))),
    ("CRUSH", shape(lambda x: math.sin(2 * math.pi * (math.floor(x * 16) + 0.5) / 16))),
    ("WIRE", spectrum({1: 1.0, 30: 0.3, 31: 0.35, 32: 0.4, 33: 0.35, 34: 0.3})),
    ("REED", formants([(1500, 0.8, 250)], 1.0)),
    ("BRASS", formants([(1100, 1.0, 400), (2500, 0.5, 500)], 0.7)),
    ("STRING", seeded(31, lambda k, r: 1.0 / k ** 1.15)),
]

assert len(WAVES) == 56 and len({n for n, _ in WAVES}) == len(WAVES)
assert all(len(n) <= 7 for n, _ in WAVES)


def main(path):
    L = ["/* generated by tools/gen_hy_waves.py */", "#pragma once", "#include <stdint.h>", ""]
    L += [f"#define HY_NWAVE {len(WAVES)}u", f"#define HY_PTS {N}u", ""]
    L += ["enum { " + ", ".join("HYW_" + re.sub(r"[^A-Z0-9]", "_", n) for n, _ in WAVES) + " };", ""]
    # (a list: hydra_edit.h's HY_ALL_NAMES follows them with the user waves' names)
    L += ["#define HY_WAVE_NAME_LIST " + ", ".join(f'"{n}"' for n, _ in WAVES), ""]
    L += ["static const int16_t HY_WAVES[HY_NWAVE][HY_PTS] = {"]
    for name, w in WAVES:
        v = finish(w)
        L.append(f"    {{ /* {name} */")
        for i in range(0, N, 16):
            L.append("        " + ", ".join(str(x) for x in v[i:i + 16]) + ",")
        L.append("    },")
    L.append("};")
    with open(path, "w") as f:
        f.write("\n".join(L) + "\n")
    print(f"gen_hy_waves: {len(WAVES)} waves x {N * 2} B = {len(WAVES) * N * 2} B -> {path}")


if __name__ == "__main__":
    import sys
    main(sys.argv[1] if len(sys.argv) > 1 else "build/gen/melodee_hy.h")
