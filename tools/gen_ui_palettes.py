"""The UI theme (run by tools/generate_assets.py).

  gen_ui_palettes.py OUT.h [--report]

Saadet has one look, STAGE: near-black, white type, grays for whatever is secondary, and one colour per engine. The
colour of the engine the sound plays is THEME (src/gfx.c theme_engine): the value being turned, curves, the engine's
tag. Every token is stored (RGB565); only text and edges are blended at run time.
  BG     the ground
  TEXT   names and values
  MID    secondary text: labels, the place's object, hints
  DIM    tertiary text: an inactive value, an unbound row, a key's number
  FAINT  the far rows of a list
  FILL   a bar's fill, an inactive curve
  LIT    a lit key, a used slot (the keyboard and slot pictures)
  OFF    a page dot not shown, beat ticks
  LINE   a bar's track, rules
  WELL   an unlit key, an empty slot
  ENG    the engines' colours: PROPHET, FM6, CZ-1, JUNO-106 (retired SID's), HYDRA
Outside the theme: the crash screen's fixed red.
GRAY (R = G = B in every token) is compiled into the host tests only (UI_TEST_PALETTE): a screen drawn in it must stay
gray, which proves the drawing takes every colour from the tokens.
Saved settings name the palette by a tagged id (PAL_TAG + index); any other id reads as the default.
--report prints the contrast of every pairing read on the screen. The tool fails on any miss.
"""
import argparse
import sys
from pathlib import Path

TOKENS = ("bg", "text", "mid", "dim", "faint", "fill", "lit", "off", "line", "well")
# name, the tokens in TOKENS' order, the engines' colours (8-bit RGB; stored as RGB565)
PALETTES = [
    ("STAGE", ((5, 5, 6), (255, 255, 255), (163, 163, 171), (122, 122, 132), (85, 85, 94), (92, 92, 102),
               (74, 74, 84), (58, 58, 66), (34, 34, 39), (28, 28, 33)),
     ((255, 107, 61), (82, 168, 255), (242, 201, 76), (185, 150, 255), (72, 214, 160))),
]
TEST_GRAY = ("GRAY", ((6, 6, 6), (255, 255, 255), (164, 164, 164), (123, 123, 123), (86, 86, 86), (93, 93, 93),
                      (75, 75, 75), (59, 59, 59), (35, 35, 35), (29, 29, 29)),
             ((180, 180, 180), (190, 190, 190), (230, 230, 230), (200, 200, 200), (210, 210, 210)))
PAL_TAG = 96                       # stored id = PAL_TAG + index (ids below: earlier firmware, read as the default)
CRASH_BG, CRASH_INK = (160, 0, 0), (255, 255, 255)
# (fg, bg, minimum contrast): what is read on the screen. ENG stands for each engine's colour
CHECKS = [("text", "bg", 15.0), ("mid", "bg", 7.0), ("dim", "bg", 4.5), ("faint", "bg", 2.5), ("eng", "bg", 4.5),
          ("text", "well", 12.0), ("mid", "line", 5.5), ("fill", "line", 2.0), ("lit", "well", 1.8),
          ("off", "bg", 1.7), ("line", "bg", 1.2)]


def to565(c, gray=False):
    """gray: a neutral colour stored with G = 2 R (the GRAY test palette's rule: exactly gray in RGB565)"""
    r, g, b = c
    if gray:
        assert r == g == b, c
        return ((r >> 3) << 11) | ((r >> 3) << 6) | (r >> 3)
    return ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)


def from565(v):
    return ((v >> 11) * 255 // 31, ((v >> 5) & 63) * 255 // 63, (v & 31) * 255 // 31)


def lum(c565):
    def lin(v):
        v /= 255.0
        return v / 12.92 if v <= 0.04045 else ((v + 0.055) / 1.055) ** 2.4
    r, g, b = from565(c565)
    return 0.2126 * lin(r) + 0.7152 * lin(g) + 0.0722 * lin(b)


def contrast(a, b):
    la, lb = lum(a), lum(b)
    return (max(la, lb) + 0.05) / (min(la, lb) + 0.05)


def row(p):
    name, tok, eng = p
    gray = p is TEST_GRAY
    t = ", ".join(f"0x{to565(c, gray):04x}" for c in tok)
    e = ", ".join(f"0x{to565(c, gray):04x}" for c in eng)
    return f'    {{"{name}", {t}, {{{e}}}}},'


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("out")
    ap.add_argument("--report", action="store_true")
    a = ap.parse_args()
    failed = []
    for p in PALETTES + [TEST_GRAY]:
        name, tok, eng = p
        gray = p is TEST_GRAY
        d = {k: to565(c, gray) for k, c in zip(TOKENS, tok)}
        for fg, bg, lim in CHECKS:
            for k, col in enumerate(eng if fg == "eng" else [None]):
                f = to565(col, gray) if col else d[fg]
                r = contrast(f, d[bg])
                label = f"{name} {fg}{k + 1 if col else ''}/{bg}"
                if a.report:
                    print(f"{label:24s} {r:5.2f} (min {lim})")
                if r < lim:
                    failed.append(f"{label} {r:.2f} < {lim}")
    out = ["/* generated by tools/gen_ui_palettes.py: the theme, RGB565 (src/gfx.c ui_pal_t) */", "#pragma once", "",
           "static const ui_pal_t UI_PALETTES[] = {", *[row(p) for p in PALETTES],
           "#ifdef UI_TEST_PALETTE", row(TEST_GRAY), "#endif", "};",
           f"#define UI_NPALETTES {len(PALETTES)}u", "#define UI_DEFAULT_INDEX 0u",
           f"#define UI_GRAY_INDEX {len(PALETTES)}u      /* (UI_TEST_PALETTE only) */",
           f"#define UI_PAL_TAG {PAL_TAG}u          /* stored id = UI_PAL_TAG + index */",
           f"#define UI_CRASH_BG 0x{to565(CRASH_BG):04x}u", f"#define UI_CRASH_INK 0x{to565(CRASH_INK):04x}u", ""]
    for f in failed:
        print("FAIL", f)
    if failed:
        sys.exit(1)
    Path(a.out).write_text("\n".join(out))


if __name__ == "__main__":
    main()
