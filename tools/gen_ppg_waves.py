"""The PPG Wave 2.2's wavetables for the PPG engine, from a local image of its wave EPROMs.

The ROM data is PPG's, not this repository's, and is never committed: the image lives in the gitignored
`private/ppg/ppg22-waves.bin` (or the path in SAADET_PPG_ROM), and the header this writes lands in the gitignored
build/gen. Without the image the header says PPG_HAVE_ROM 0 and carries no data, so every build still passes.

The image is the first 17,152 bytes of the 2.2's wave EPROMs (identical in the 2.2 V3 and EVU 1.0 dumps):
  0..767     the directory: per table one ignored byte, then (wave, slot) pairs up to the one whose slot is 0x3C;
             tables 0..27, then the Upper Wavetable. 28 and 29 are computed by the synth and are not listed.
  768..      256 waves of 64 unsigned 8-bit samples, the first half of a cycle; the second half is the first
             backwards and negated about 0x80.
Slots between two keys are the straight blend of those keys; slots 60..63 are the synth's triangle, pulse, square
and saw, so a table's key at 60 only steers the blend of 49..59 (the engine builds those, not this tool).
The parse was checked against Hermann Seib's catalog of the V4 wavetables: every table's stored slots match.

WAVETABLE 31's natural sounds (the owner's manual, 7.3.6: a piano and a saxophone): the OS (V3 and V5 alike, its
table load at 0xEE00 / 0xA980) copies CPU 0x8000..0x8FFF (the piano, EPROM 8) then 0xF000..0xFEFF (the saxophone,
EPROM E) into the wave memory from its start, 7,936 bytes, and leaves the last 256 (the upper table's four standard
waves). EPROM 8 is read from the local V3 dump (private/ppg/dumps/ppg22v3.zip, Intel HEX); the saxophone from the V5
image (the V3's EPROM E holds the same bytes).
"""
import hashlib
import os
import sys
import zipfile
from pathlib import Path

SRC = Path(__file__).resolve().parents[1]
DEFAULT = SRC / "private/ppg/ppg22-waves.bin"
SIZE = 768 + 256 * 64
SHA256 = "9c8ddb051d717a46a3bda6221608dc05515af9442f681ef744bd9bdf7f149347"
NTABLE = 29                                         # 0..27 and the Upper Wavetable (the engine's table 30)
END = 0x3C


def parse(img):
    """the directory: a list of tables, each a list of (slot, wave)"""
    tables, i = [], 0
    for _ in range(NTABLE):
        i += 1                                      # the table's number: unreliable, unused
        keys = []
        while True:
            wave, slot = img[i], img[i + 1]
            i += 2
            keys.append((slot, wave))
            if slot >= END:
                break
        slots = [s for s, _ in keys]
        assert slots[0] == 0 and slots[-1] == END and slots == sorted(set(slots)), f"table {len(tables)}: {slots}"
        tables.append(keys)
    assert i <= 768
    return tables


def header(img):
    out = ["/* Generated by tools/gen_ppg_waves.py from a local image of the PPG Wave 2.2's wave EPROMs.",
           " * The data below is PPG's (Palm Products GmbH), not covered by this repository's licence; keep it out",
           " * of version control. */",
           "#pragma once", "#include <stdint.h>"]
    if img is None:
        return "\n".join(out + ["#define PPG_HAVE_ROM 0", ""])
    tables = parse(img)
    at, keys = [], []
    for t in tables:
        at.append(len(keys))
        keys.extend(t)
    at.append(len(keys))
    out += ["#define PPG_HAVE_ROM 1",
            f"#define PPG_ROM_TABLES {NTABLE}u          /* 0..27, then the Upper Wavetable */",
            f"#define PPG_ROM_KEYS {len(keys)}u",
            "/* table t's keys are PPG_KEY_SLOT/WAVE[PPG_KEY_AT[t] .. PPG_KEY_AT[t + 1] - 1], slots ascending, the last 60 */",
            "static const uint16_t PPG_KEY_AT[PPG_ROM_TABLES + 1] = {" + ", ".join(map(str, at)) + "};",
            "static const uint8_t PPG_KEY_SLOT[PPG_ROM_KEYS] = {" + ", ".join(str(s) for s, _ in keys) + "};",
            "static const uint8_t PPG_KEY_WAVE[PPG_ROM_KEYS] = {" + ", ".join(str(w) for _, w in keys) + "};",
            "/* half cycles: 64 unsigned samples, 0x80 the centre */",
            "static const uint8_t PPG_WAVES[256][64] = {"]
    for w in range(256):
        row = img[768 + 64 * w:768 + 64 * w + 64]
        out.append("    {" + ",".join(str(b) for b in row) + "},")
    out.append("};")
    eg = envelope_tables()
    if eg:
        out += ["#define PPG_HAVE_EG 1",
                "static const uint8_t PPG_EG_FRAC[32] = {" + ",".join(map(str, eg[0])) + "};",
                "static const uint8_t PPG_EG_WAIT[32] = {" + ",".join(map(str, eg[1])) + "};"]
    else:
        out.append("#define PPG_HAVE_EG 0")
    smp = samples()
    if smp:
        out += ["#define PPG_HAVE_SAMPLE 1",
                f"#define PPG_SAMPLE_BYTES {len(smp)}u     /* WAVETABLE 31: the piano, then the saxophone, as the OS copies them */",
                "static const uint8_t PPG_SAMPLE[PPG_SAMPLE_BYTES] = {"]
        out += ["    " + ",".join(str(b) for b in smp[i:i + 64]) + "," for i in range(0, len(smp), 64)]
        out.append("};")
    else:
        out.append("#define PPG_HAVE_SAMPLE 0")
    return "\n".join(out) + "\n"


OS = SRC / "private/ppg/ppg22-os-v5.bin"          # the 2.2's V5 OS, 0xA000..0xFFFF (its three EPROMs in order)
OS_SHA256 = "53ebed7132337f048783ed78e682f4668c6c12f70cf726f9db442d646370d6b1"
EG_FRAC, EG_WAIT = 0xA71A, 0xA6FA                  # the envelopes' rate tables (the OS's rate routine at 0xA6DA)


def envelope_tables():
    """the envelopes' 32 rates: the fraction of the remaining distance a step moves (/256) and the passes it waits
    after it (the OS's envelope loop: attack index ATTACK / 4, decay and release DECAY / 2, RELEASE / 2)"""
    if not OS.exists():
        return None
    data = OS.read_bytes()
    if hashlib.sha256(data).hexdigest() != OS_SHA256:
        raise SystemExit(f"gen_ppg_waves: {OS} is not the expected PPG Wave 2.2 V5 OS image")
    at = lambda a: list(data[a - 0xA000:a - 0xA000 + 32])
    return at(EG_FRAC), at(EG_WAIT)


V3_ZIP = SRC / "private/ppg/dumps/ppg22v3.zip"
EPROM8 = "PPG Wave 2.2 Version v3/w22_381.bin"
PIANO_SHA256 = "239d3fd1ca044de061cbf9b5970f707636ec8abe5b7003fc5754cfbad3dbff5e"
SAX_SHA256 = "28fbaf7f33d1ffe0a0b2ba9d8e845a59e87b582164f6232a23427561c4bad07b"


def intel_hex(text, size=8192):
    out = bytearray(size)
    for line in text.splitlines():
        line = line.strip()
        if line.startswith(":") and int(line[7:9], 16) == 0:
            n, at = int(line[1:3], 16), int(line[3:7], 16)
            out[at:at + n] = bytes.fromhex(line[9:9 + 2 * n])
    return bytes(out)


def samples():
    """WAVETABLE 31's wave memory, as the OS fills it: the piano (4,096 bytes), then the saxophone (3,840)"""
    if not OS.exists() or not V3_ZIP.exists():
        return None
    with zipfile.ZipFile(V3_ZIP) as z:
        piano = intel_hex(z.read(EPROM8).decode("ascii"))[:4096]
    sax = OS.read_bytes()[0xF000 - 0xA000:0xFF00 - 0xA000]
    if hashlib.sha256(piano).hexdigest() != PIANO_SHA256 or hashlib.sha256(sax).hexdigest() != SAX_SHA256:
        raise SystemExit("gen_ppg_waves: the 2.2's natural sounds (EPROM 8 of the V3 dump, the V5 image) are not as expected")
    return piano + sax


def load():
    path = Path(os.environ.get("SAADET_PPG_ROM", DEFAULT))
    if not path.exists():
        return None, path
    data = path.read_bytes()[:SIZE]
    digest = hashlib.sha256(data).hexdigest()
    if len(data) != SIZE or digest != SHA256:
        raise SystemExit(f"gen_ppg_waves: {path} is not the expected PPG Wave 2.2 wave image (sha256 {digest})")
    return data, path


def main(argv):
    if len(argv) != 2:
        raise SystemExit("usage: gen_ppg_waves.py OUT.h")
    img, path = load()
    Path(argv[1]).write_text(header(img))
    print(f"gen_ppg_waves: {'PPG wavetables from ' + str(path) if img else 'no PPG image (' + str(path) + '), stub header'}")


if __name__ == "__main__":
    main(sys.argv)
